'use strict';

/**
 * Bundles for the CDN encryption live test.
 *
 * The real deployment puts a CDN in front of the Iran origin. Here the foreign
 * namespace dials the Iran namespace directly on :8443, so the test exercises
 * the exact chain that matters for scenario 3:
 *
 *   foreign: ReverseClient -> EncryptionClient -> MuxClient -> HttpClient
 *            -> TlsClient -> TcpConnector(10.200.0.2:8443)
 *   iran:    TcpListener(8443) -> TlsServer -> HttpServer -> MuxServer
 *            -> EncryptionServer -> ReverseServer
 *
 * It is the same WebSocket/TLS carrier with a real AEAD layer inside it; only
 * the CDN edge is removed. The self-signed certificate is generated by the
 * harness and the client uses verify:false.
 *
 *   node test/live/cdn-encrypt-generate.js
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const templates = require('../../lib/templates');
const { buildBundle, resolveOptions } = require('../../lib/build');
const { Store } = require('../../lib/store');

const OUT = path.join(__dirname, 'out-cdn');
const IRAN_HOST = '10.200.0.2';
const FOREIGN_HOST = '10.200.0.3';
const SVC_HOST = '10.200.0.1';
const ENTRY_PORT = 8486;
const ORIGIN_PORT = 8443;
const CERT_DIR = '/root/wwcdn/cert';

function writeSide(name, files) {
  const dir = path.join(OUT, name);
  fs.mkdirSync(path.join(dir, 'log'), { recursive: true });
  for (const [file, text] of Object.entries(files)) {
    const target = path.join(dir, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
  }
}

function main() {
  if (!templates.get('cdn-reverse-wss')) throw new Error('cdn-reverse-wss is missing');

  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'wwcdn-'));
  const store = new Store(dataDir);
  store.addServer({ id: 'srv-iran', name: 'Iran', role: 'iran', host: IRAN_HOST });
  store.addServer({ id: 'srv-exit', name: 'Exit', role: 'foreign', host: FOREIGN_HOST });

  const options = resolveOptions('cdn-reverse-wss', {
    // Direct origin dial: the test has no CDN edge. The Host/SNI stays a real
    // name so the TLS server and the HTTP layer see the same value.
    cdnHost: 'example.com',
    cdnPort: ORIGIN_PORT,
    edgeAddress: IRAN_HOST,
    originTls: true,
    httpVersion: '1.1',
    wsPath: '/ws',
    expectedHost: '',
    userPort: ENTRY_PORT,
    originPort: ORIGIN_PORT,
    listenAddress: '0.0.0.0',
    minimumUnused: 8,
    useMux: true,
    muxMode: 'timer',
    muxConnectionDurationMs: 300000,
    domain: 'example.com',
    certMode: 'none',
    certPath: `${CERT_DIR}/fullchain.pem`,
    keyPath: `${CERT_DIR}/privkey.pem`,
    verify: false,
    localServiceAddress: SVC_HOST,
    finalPort: 9001,
    linkEncryption: true,
    linkEncryptAlgorithm: 'chacha20-poly1305',
    _core: { workers: 2, ramProfile: 'minimal' },
    // Concrete values make a failure point at the node, not at the variable
    // loader (the relay live test already covers that path).
    useVariables: false,
  });

  const tunnel = store.addTunnel({
    name: 'cdn-encrypted-live',
    template: 'cdn-reverse-wss',
    targetServers: { iran: 'srv-iran', foreign: 'srv-exit' },
    options,
  });
  const built = buildBundle(store, tunnel);
  if (!built.ok) throw new Error(`build failed: ${built.problems.join('; ')}`);

  const parse = (side) => {
    const file = Object.keys(built.bundles[side]).find((f) => f.startsWith('configs/'));
    const text = built.bundles[side][file];
    return { file, cfg: JSON.parse(text) };
  };
  const iran = parse('iran');
  const foreign = parse('foreign');
  const types = (cfg) => cfg.nodes.map((n) => n.type);
  for (const [side, cfg] of [['iran', iran.cfg], ['foreign', foreign.cfg]]) {
    if (!types(cfg).includes(side === 'iran' ? 'EncryptionServer' : 'EncryptionClient')) {
      throw new Error(`${side}: encryption node is missing`);
    }
  }

  fs.rmSync(OUT, { recursive: true, force: true });
  writeSide('iran', built.bundles.iran);
  writeSide('foreign', built.bundles.foreign);
  fs.writeFileSync(
    path.join(OUT, 'meta.json'),
    JSON.stringify(
      {
        entry: { host: IRAN_HOST, port: ENTRY_PORT },
        origin: { host: IRAN_HOST, port: ORIGIN_PORT },
        exit: FOREIGN_HOST,
        service: `tcp-echo:9001`,
        encryption: {
          password: built.options.linkEncryptPassword,
          algorithm: built.options.linkEncryptAlgorithm,
        },
        files: { iran: iran.file, foreign: foreign.file },
      },
      null,
      2,
    ),
  );

  console.log(
    JSON.stringify(
      {
        out: OUT,
        entry: `${IRAN_HOST}:${ENTRY_PORT}`,
        origin: `${IRAN_HOST}:${ORIGIN_PORT}`,
        encryption: 'on',
        iranChain: iran.cfg.nodes.map((n) => n.type),
        foreignChain: foreign.cfg.nodes.map((n) => n.type),
      },
      null,
      1,
    ),
  );
}

main();
