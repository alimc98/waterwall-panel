#!/usr/bin/env python3
"""Live proof of the optional AEAD layer inside the CDN tunnel.

The real CDN edge is replaced by a direct dial from the foreign namespace to
the Iran origin. Everything that matters for scenario 3 stays in the chain:

    foreign  ReverseClient -> EncryptionClient -> MuxClient -> HttpClient
             -> TlsClient -> TcpConnector(10.200.0.2:8443)
    iran     TcpListener(8443) -> TlsServer -> HttpServer -> MuxServer
             -> EncryptionServer -> ReverseServer

The self-signed certificate is generated by the harness; the foreign TlsClient
uses verify:false. A TCP echo service on the host bridge is the final target.

    cd /root/wwcdn/remote && python3 cdn_encrypt.py
"""

import json
import os
import shutil
import signal
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(ROOT)
OUT = os.path.join(BASE, "out-cdn")
RUN = os.path.join(BASE, "run-cdn")

import run

with open(os.path.join(OUT, "meta.json"), encoding="utf-8") as f:
    META = json.load(f)
ENTRY = META["entry"]
PROBES = 10


def deploy(name):
    src = os.path.join(OUT, name)
    dst = os.path.join(RUN, name)
    shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(src, dst)
    os.makedirs(os.path.join(dst, "log"), exist_ok=True)
    return dst


def start_service():
    try:
        s = socket_create((run.HOST_IP, 9001))
        s.close()
        return None, True
    except OSError:
        pass
    log = open(os.path.join(BASE, "svc-cdn.log"), "w")
    p = subprocess.Popen(
        ["python3", os.path.join(ROOT, "svc.py")],
        stdout=log,
        stderr=subprocess.STDOUT,
        start_new_session=True,
    )
    ok, why = run.wait_for_service()
    if not ok:
        stop_process(p)
        return None, why
    return p, "started"


def socket_create(addr):
    import socket

    return socket.create_connection(addr, timeout=1)


def stop_process(p):
    if not p:
        return
    try:
        os.killpg(os.getpgid(p.pid), signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        pass


def parse_side(dirname):
    path = os.path.join(RUN, dirname, META["files"][dirname])
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def fatal_lines(side_dir):
    text = run.read_console(side_dir)
    return [ln.strip() for ln in text.splitlines() if "FATAL" in ln]


def main():
    result = {"id": "cdn-encryption-live", "steps": [], "ok": False}
    procs = {}
    svc = None

    try:
        run.ensure_cert()
        os.makedirs(RUN, exist_ok=True)
        run.del_namespaces()
        run.del_bridge()
        run.ensure_bridge()
        run.enable_nat()

        svc, svc_state = start_service()
        if not svc and svc_state is not True:
            result["error"] = f"test service: {svc_state}"
            return result
        result["service"] = svc_state

        ok, err = run.setup_netns()
        if not ok:
            result["error"] = err
            return result

        dirs = {"iran": deploy("iran"), "foreign": deploy("foreign")}
        iran_cfg = parse_side("iran")
        foreign_cfg = parse_side("foreign")
        iran_types = [n["type"] for n in iran_cfg["nodes"]]
        foreign_types = [n["type"] for n in foreign_cfg["nodes"]]
        if "EncryptionServer" not in iran_types or "EncryptionClient" not in foreign_types:
            result["error"] = "the deployed configs do not contain the encryption nodes"
            return result

        # Both peers must carry the same password/algorithm, and the encryption
        # node must sit between the carrier and the reverse node.
        def enc(cfg, kind):
            return next((n for n in cfg["nodes"] if n["type"] == kind), None)

        ie = enc(iran_cfg, "EncryptionServer")
        fe = enc(foreign_cfg, "EncryptionClient")
        result["encryption"] = {
            "iran": {k: ie["settings"].get(k) for k in ("password", "algorithm", "salt", "kdf-iterations")},
            "foreign": {k: fe["settings"].get(k) for k in ("password", "algorithm", "salt", "kdf-iterations")},
            "match": ie["settings"].get("password") == fe["settings"].get("password")
            and ie["settings"].get("algorithm") == fe["settings"].get("algorithm"),
        }
        result["steps"].append(
            {
                "step": "encryption peers agree on password, algorithm, salt and KDF",
                "ok": result["encryption"]["match"],
                "detail": json.dumps(result["encryption"]),
            }
        )

        procs["iran"] = run.start_core(run.IRAN_NS, dirs["iran"])
        run.wait_for_config_load(dirs["iran"])
        time.sleep(1.0)
        result["iranListeners"] = run.listeners_in(run.IRAN_NS)
        if ENTRY["port"] not in result["iranListeners"] or META["origin"]["port"] not in result["iranListeners"]:
            result["error"] = (
                f"the origin never bound :{ENTRY['port']} and :{META['origin']['port']}; "
                f"listeners={result['iranListeners']}"
            )
            return result

        procs["foreign"] = run.start_core(run.FOREIGN_NS, dirs["foreign"])
        run.wait_for_config_load(dirs["foreign"])
        time.sleep(1.0)

        ok_count = 0
        details = []
        for _ in range(PROBES):
            r = run.probe("tcp", ENTRY["host"], ENTRY["port"], "")
            if r.get("ok"):
                ok_count += 1
            else:
                details.append(r.get("detail"))
            time.sleep(0.2)
        result["probes"] = {"ok": ok_count, "of": PROBES}
        result["steps"].append(
            {
                "step": f"{PROBES} user connections cross the encrypted CDN chain",
                "ok": ok_count == PROBES,
                "detail": json.dumps(result["probes"]) + (f" errors={details}" if details else ""),
            }
        )

        fatal = {}
        for name, d in dirs.items():
            bad = fatal_lines(d)
            if bad:
                fatal[name] = bad[:5]
        result["fatal"] = fatal
        result["steps"].append(
            {
                "step": "no FATAL in either core",
                "ok": not fatal,
                "detail": json.dumps(fatal),
            }
        )

        result["ok"] = all(s["ok"] for s in result["steps"])
        return result
    finally:
        for p in list(procs.values()):
            try:
                run.stop_core(*p)
            except Exception:  # noqa: BLE001
                pass
        run.del_namespaces()
        run.del_bridge()
        stop_process(svc)
        run.disable_nat()


if __name__ == "__main__":
    res = main()
    out = os.path.join(BASE, "cdn-encrypt-result.json")
    try:
        with open(out, "w", encoding="utf-8") as f:
            json.dump(res, f, indent=2, ensure_ascii=False)
    except OSError:
        pass
    for step in res.get("steps", []):
        print(f"[{'OK  ' if step['ok'] else 'FAIL'}] {step['step']}: {step['detail']}")
    if res.get("error"):
        print(f"ERROR: {res['error']}")
    print(json.dumps(res, ensure_ascii=False))
    print(f"\nwrote {out}")
    sys.exit(0 if res.get("ok") else 1)
